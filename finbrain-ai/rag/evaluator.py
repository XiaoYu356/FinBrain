def compare_evaluations(baseline: Dict, current: Dict) -> Dict:
    def calc_improvement(old_val: float, new_val: float) -> str:
        if old_val == 0:
            return "N/A"
        change = (new_val - old_val) / old_val * 100
        sign = "+" if change >= 0 else ""
        return f"{sign}{change:.1f}%"
    
    return {
        "baseline": baseline,
        "current": current,
        "improvement": {
            "precision": calc_improvement(baseline.get("precision", 0), current.get("precision", 0)),
            "recall": calc_improvement(baseline.get("recall", 0), current.get("recall", 0)),
            "f1_score": calc_improvement(baseline.get("f1_score", 0), current.get("f1_score", 0)),
            "faithfulness": calc_improvement(baseline.get("faithfulness", 0), current.get("faithfulness", 0)),
            "answer_relevancy": calc_improvement(baseline.get("answer_relevancy", 0), current.get("answer_relevancy", 0)),
            "context_recall": calc_improvement(baseline.get("context_recall", 0), current.get("context_recall", 0)),
            "context_precision": calc_improvement(baseline.get("context_precision", 0), current.get("context_precision", 0)),
        }
    }
